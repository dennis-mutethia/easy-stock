"""Builds the Statement of Account PDF (bank-ready, A4 portrait)."""
import io
from datetime import datetime

import pytz
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (BaseDocTemplate, Frame, PageTemplate, Paragraph,
                                Spacer, Table, TableStyle)

INK = colors.HexColor('#162422')
MUTED = colors.HexColor('#5b6b68')
RULE = colors.HexColor('#bccbc8')
HEAD_BG = colors.HexColor('#e7f0ee')
TOTAL_BG = colors.HexColor('#f1f7f5')
GAIN = colors.HexColor('#1b7f45')
LOSS = colors.HexColor('#c0392b')


def _num(value):
    try:
        return float(value or 0)
    except (TypeError, ValueError):
        return 0.0


def _money(value):
    return "{:,.0f}".format(_num(value))


def _date_text(value):
    if hasattr(value, 'strftime'):
        return value.strftime('%d %b %Y')
    try:
        return datetime.strptime(str(value)[:10], '%Y-%m-%d').strftime('%d %b %Y')
    except ValueError:
        return str(value)


def build_statement_pdf(shop_name, from_date, to_date, statements):
    buffer = io.BytesIO()
    now = datetime.now(pytz.timezone("Africa/Nairobi")).strftime('%d %b %Y, %H:%M')

    title = ParagraphStyle('title', fontName='Helvetica-Bold', fontSize=18, leading=22, textColor=INK)
    shop = ParagraphStyle('shop', fontName='Helvetica-Bold', fontSize=12, leading=16, textColor=INK)
    meta = ParagraphStyle('meta', fontName='Helvetica', fontSize=9.5, leading=13, textColor=MUTED)

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont('Helvetica', 8)
        canvas.setFillColor(MUTED)
        canvas.drawString(15 * mm, 10 * mm, f"Generated by EasyStock on {now}")
        canvas.drawRightString(A4[0] - 15 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = BaseDocTemplate(
        buffer, pagesize=A4,
        leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=18 * mm,
        title="Statement of Account", author="EasyStock",
    )
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id='body')
    doc.addPageTemplates([PageTemplate(id='main', frames=[frame], onPage=footer)])

    story = [
        Paragraph("Statement of Account", title),
        Spacer(1, 3 * mm),
        Paragraph(shop_name or '', shop),
        Paragraph(f"Period: {_date_text(from_date)} to {_date_text(to_date)}", meta),
        Paragraph("All amounts in KES", meta),
        Spacer(1, 6 * mm),
    ]

    # one line per non-zero amount, in the same order as the on-screen statement
    rows = [['Date', 'Details', 'Money in', 'Money out']]
    total_in = total_out = 0.0
    date_rows = []  # first row of each date, for a light rule between dates
    for st in statements:
        sales, purchases, expenses = _num(st.sales), _num(st.purchases), _num(st.expenses)
        total_in += sales
        total_out += purchases + expenses
        lines = []
        if sales > 0:
            lines.append(('Sales', _money(sales), ''))
        if purchases > 0:
            lines.append(('Purchases', '', _money(purchases)))
        if expenses > 0:
            lines.append(('Expenses', '', _money(expenses)))
        for n, (label, money_in, money_out) in enumerate(lines):
            if n == 0:
                date_rows.append(len(rows))
            rows.append([_date_text(st.date) if n == 0 else '', label, money_in, money_out])

    if len(rows) == 1:
        rows.append(['', 'No transactions in this period', '', ''])

    body_end = len(rows) - 1
    rows.append(['Totals', '', _money(total_in), _money(total_out)])
    balance = total_in - total_out
    rows.append(['Balance', '',
                 ('+' + _money(balance)) if balance > 0 else '',
                 ('-' + _money(-balance)) if balance < 0 else ''])

    widths = [32 * mm, doc.width - 32 * mm - 36 * mm - 36 * mm, 36 * mm, 36 * mm]
    table = Table(rows, colWidths=widths, repeatRows=1)
    style = [
        ('FONTNAME', (0, 0), (-1, -1), 'Helvetica'),
        ('FONTSIZE', (0, 0), (-1, -1), 9.5),
        ('TEXTCOLOR', (0, 0), (-1, -1), INK),
        ('ALIGN', (2, 0), (-1, -1), 'RIGHT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        # header
        ('BACKGROUND', (0, 0), (-1, 0), HEAD_BG),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('LINEBELOW', (0, 0), (-1, 0), 0.8, RULE),
        # ledger rule between money in and money out
        ('LINEBEFORE', (3, 0), (3, -1), 1.2, RULE),
        ('BOX', (0, 0), (-1, -1), 0.6, RULE),
        # totals: rule above, bold
        ('BACKGROUND', (0, body_end + 1), (-1, -1), TOTAL_BG),
        ('FONTNAME', (0, body_end + 1), (-1, -1), 'Helvetica-Bold'),
        ('LINEABOVE', (0, body_end + 1), (-1, body_end + 1), 0.6, INK),
    ]
    for r in date_rows[1:]:
        style.append(('LINEABOVE', (0, r), (-1, r), 0.4, colors.HexColor('#d9e3e1')))
    if balance > 0:
        style.append(('TEXTCOLOR', (2, len(rows) - 1), (2, len(rows) - 1), GAIN))
    elif balance < 0:
        style.append(('TEXTCOLOR', (3, len(rows) - 1), (3, len(rows) - 1), LOSS))
    table.setStyle(TableStyle(style))
    story.append(table)

    doc.build(story)
    return buffer.getvalue()